import { bar, progress } from './progress.mjs';

const SUM_BEGIN = '<!-- keel:summary -->';
const SUM_END = '<!-- /keel:summary -->';

/** The project summary between the summary markers of the state file, or null. */
export function readSummary(project) {
  const file = project.paths.state;
  if (!fs.existsSync(file)) return null;
  const text = fs.readFileSync(file, 'utf8');
  const a = text.indexOf(SUM_BEGIN);
  const b = text.indexOf(SUM_END);
  if (a === -1 || b === -1) return null;
  const s = text.slice(a + SUM_BEGIN.length, b).trim();
  return s || null;
}

/** Writes the project summary: at most 40 lines, the part every session reads first. */
export function writeSummary(project, summary) {
  const body = String(summary ?? '').trim();
  if (body.length < 40) fail('The summary is too short: say what the project is, for whom, its main parts and its stack.');
  const lines = body.split('\n');
  if (lines.length > 40) fail(`The summary has ${lines.length} lines; keep it to 40. Detail belongs in the docs it links to.`);
  const file = project.paths.state;
  let text = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '# Project state\n';
  const block = `${SUM_BEGIN}\n${body}\n${SUM_END}`;
  const a = text.indexOf(SUM_BEGIN);
  const b = text.indexOf(SUM_END);
  if (a !== -1 && b !== -1) text = text.slice(0, a) + block + text.slice(b + SUM_END.length);
  else {
    const firstBreak = text.indexOf('\n## ');
    const insert = `\n## The project\n\n${block}\n`;
    text = firstBreak === -1 ? text + insert : text.slice(0, firstBreak) + '\n' + insert + text.slice(firstBreak);
  }
  writeText(file, text);
  return { lines: lines.length };
}

const BEGIN = '<!-- keel:state -->';
const END = '<!-- /keel:state -->';

export function stateBlock(project) {
  const features = loadFeatures(project);
  const store = loadQuestions(project);
  const proposed = loadDecisions(project).filter((r) => r.status === 'proposed');
  let s = `${BEGIN}\n<!-- Generated by keel. Do not edit between these markers: run \`keel render\`. -->\n\n### Features\n\n`;
  const ids = Object.keys(features);
  const p = progress(project);
  if (!ids.length) s += 'None yet.\n';
  else {
    s += `Overall: ${bar(p.overall)} ${p.overall}% · checks with a test ${p.checks.covered}/${p.checks.total}\n\n`;
    s += '| Feature | Status | Progress | Checks tested | Verified | Open work | Decisions |\n|---|---|---|---|---|---|---|\n';
    const byFeature = new Map(p.features.map((f) => [f.id, f]));
    for (const st of STATUSES) {
      for (const id of ids.filter((i) => features[i].status === st)) {
        const f = features[id];
        const fp = byFeature.get(id);
        const prog = fp ? `${bar(fp.percent)} ${fp.percent}%` : '—';
        const ver = fp ? { yes: 'yes', stale: 'stale', no: '—' }[fp.verified] : '—';
        s += `| \`${id}\` ${f.title} | ${f.status} | ${prog} | ${fp ? `${fp.covered}/${fp.checks}` : '—'} | ${ver} | ${(f.work ?? []).length} | ${(f.decisions ?? []).join(', ') || '—'} |\n`;
      }
    }
  }
  const work = ids.flatMap((id) => (features[id].work ?? []).map((w) => `- \`${id}\`: ${w.text} (${w.from}, ${w.added})`));
  s += `\n### Work to build from answers\n\n${work.length ? work.join('\n') + '\n' : 'None.\n'}`;
  const owner = store.open.filter((q) => q.kind === 'product');
  s += `\n### Waiting for the owner\n\n`;
  s += owner.length ? owner.map((q) => `- Q-${q.id}: ${q.question}`).join('\n') + '\n' : 'Nothing.\n';
  const prodProposed = proposed.filter((r) => r.kind === 'product');
  if (prodProposed.length) s += prodProposed.map((r) => `- ${r.id} (proposed, needs the owner to accept): ${r.title}`).join('\n') + '\n';
  s += END;
  return s;
}

export function renderStateText(project, current) {
  const block = stateBlock(project);
  const a = current.indexOf(BEGIN);
  const b = current.indexOf(END);
  if (a === -1 || b === -1) return current;
  return current.slice(0, a) + block + current.slice(b + END.length);
}

export function renderState(project) {
  const file = project.paths.state;
  if (!fs.existsSync(file)) return false;
  const text = fs.readFileSync(file, 'utf8');
  const next = renderStateText(project, text);
  if (next !== text) writeText(file, next);
  return true;
}

/** A short briefing for the start of a session: at most a dozen lines. */
export function brief(project) {
  const { cfg } = project;
  const features = loadFeatures(project);
  const store = loadQuestions(project);
  const scope = loadScope(project);
  const records = loadDecisions(project);
  const count = (st) => Object.values(features).filter((f) => f.status === st).length;
  const owner = store.open.filter((q) => q.kind === 'product');
  const lines = [
    `keel ${version()} · ${cfg.name || 'project'} · mode ${cfg.mode}${cfg.pattern ? ` · pattern ${cfg.pattern}` : ''}`,
    `Features: ${STATUSES.filter(count).map((s) => `${count(s)} ${s}`).join(', ') || 'none'}. Decisions: ${records.length} (${records.filter((r) => r.status === 'proposed').length} proposed).`,
    `Open questions: ${owner.length} for the owner, ${store.open.length - owner.length} engineering.`,
    ownerLine(project),
    `Progress: ${progress(project).overall}% overall.`,
    architectureLine(project),
    ...heldLine(project, features),
    scope ? `Scope: ${scope.feature ?? '(deps only)'}${scope.files ? ` — ${scope.files.join(', ')}` : ''}${scope.deps.length ? ` — deps allowed by ${scope.deps.join(', ')}` : ''}.` : 'Scope: none active.',
    'Rules: the owner states a rule → `/keel:decide` before building. Product questions → `/keel:ask`, in its pattern. Tests cite `Covers:`. Done means `keel check` passes.',
  ];
  const summary = readSummary(project);
  if (summary) {
    const s = summary.split('\n');
    lines.splice(1, 0, '', 'The project:', ...s.slice(0, 15), ...(s.length > 15 ? [`… (${s.length - 15} more lines in ${project.cfg.state})`] : []), '');
  } else lines.push('No project summary yet: run /keel:adopt (existing code) or give the project brief and register it.');
  return lines.join('\n');
}

/** One line for the brief: the modules and where the rules are, or that none are defined. */
function architectureLine(project) {
  const names = Object.keys(loadArchitecture(project).modules);
  if (!names.length) return 'Architecture: no modules defined. Before the first feature, settle the stack and layout with the owner, record them with `/keel:decide`, and add the modules with `keel module add`.';
  return `Architecture: ${names.length} modules (${names.join(', ')}); each imports only what docs/ARCHITECTURE.md allows. New code goes in a module.`;
}

/** Who decides product rules, and whether that is the person in this session (by git identity on a team). */
function ownerLine(project) {
  const me = sessionOwner(project);
  const names = ownerNames(project.cfg).join(', ');
  if (me) return `Owner: the person in this session is the owner (${me.owner}, by ${me.by}); product rules they state are accepted with --by "${me.owner}" and their quote.`;
  return `Owner: ${names}. The person in this session is not an owner${project.cfg.owners.some((o) => /<.+>/.test(o)) ? ' (their git identity matches no owner)' : ''}: a product rule they state is written --status proposed and asked with /keel:ask; only the owner's own session accepts it.`;
}

/** Features other people hold right now, so a session does not start on someone else's work. */
function heldLine(project, features) {
  const held = Object.entries(features).filter(([, f]) => f.holder && !isHolder(project, f.holder));
  if (!held.length) return [];
  return [`Held by others: ${held.map(([id, f]) => `${id} (${f.holder.by.replace(/ <.*>$/, '')}, since ${f.holder.since})`).join('; ')}. Do not start on these without agreeing first.`];
}
